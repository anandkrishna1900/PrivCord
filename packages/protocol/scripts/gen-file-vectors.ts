/**
 * Generates docs/file-vectors.json: ground truth from the TypeScript file/reply/privacy code that the
 * Android (Kotlin) port must reproduce byte for byte. Run: `npx vite-node scripts/gen-file-vectors.ts`
 * from packages/protocol.
 */
import { writeFileSync } from 'node:fs';
import { entropyToMnemonic } from '@scure/bip39';
import { wordlist } from '@scure/bip39/wordlists/english.js';
import {
  FILE_CHUNK_BYTES,
  deriveIdentityFromPhrase,
  deriveInvite,
  sealInvite,
  uidFromDh,
  type ContactCard as Card,
  acceptsDirect,
  canStartDirect,
  createOutgoingMessage,
  createPeerMessageFrame,
  fileChunks,
  makeFileOffer,
  makeReplyRef,
  sanitizeFileName,
  sanitizeMime,
  type ContactTrustLevel,
} from '../src';

const bytes = Uint8Array.from({ length: FILE_CHUNK_BYTES * 2 + 777 }, (_, i) => (i * 131 + 17) & 0xff);
const offer = await makeFileOffer({
  messageId: 'file-vector-1',
  groupId: 'group-xyz',
  name: 'Report ../final?.pdf',
  mime: 'application/pdf',
  bytes,
  clientCreatedAt: 1_700_000_000_000,
  replyTo: { id: 'orig-1', author: 'uid-a', preview: 'quoted text' },
});
const chunks = [...fileChunks('file-vector-1', bytes)];

const names = [
  '../../etc/passwd',
  'C:\\Windows\\evil.exe',
  'a\u0000b\nc.txt',
  '   ',
  '.hidden',
  'x'.repeat(300) + '.png',
  'photo 1.jpeg',
];
const mimes = ['text/html; charset=utf-8', 'IMAGE/PNG', 'application/pdf', 'nonsense', 'a/b'];

const original = createOutgoingMessage({ senderId: 'uid-a', text: 'x'.repeat(500), messageId: 'orig-long' });
const reply = createOutgoingMessage({ senderId: 'uid-b', text: 'yes', messageId: 'reply-1', now: 1_700_000_000_001, replyTo: makeReplyRef(original) });

const trusts: ContactTrustLevel[] = ['verified', 'introduced'];
const privacy: { trust: string; mine: boolean; peer: boolean | null; canStart: boolean; accepts: boolean }[] = [];
for (const trust of trusts) for (const mine of [false, true]) for (const peer of [undefined, false, true]) {
  privacy.push({ trust, mine, peer: peer ?? null, canStart: canStartDirect(trust, mine, peer), accepts: acceptsDirect(trust, mine) });
}

// A six-word invite made by the TypeScript side: Kotlin must derive the same mailbox and open the blob.
const inviteWords = ['apple', 'river', 'tiger', 'moon', 'cloud', 'seven'];
const inviter = (await deriveIdentityFromPhrase(entropyToMnemonic(new Uint8Array(16).fill(0x51), wordlist))).identity;
const inviterCard: Card = { v: 1, sign: inviter.signKey.pubJwk, dh: inviter.dhKey.pubJwk, proof: inviter.identityProof, name: 'Ivy' };
const inviterUid = await uidFromDh(inviter.dhKey.pubJwk);
const rv = await deriveInvite(inviteWords);
const inviteBlob = await sealInvite({ rendezvous: rv, kind: 'card', card: inviterCard, uid: inviterUid, signPriv: inviter.signKey.privJwk });

writeFileSync(
  new URL('../../../docs/file-vectors.json', import.meta.url),
  JSON.stringify(
    {
      note: 'Generated by packages/protocol/scripts/gen-file-vectors.ts. Do not edit by hand.',
      file: { size: bytes.length, offer, chunks },
      sanitizeNames: names.map((n) => [n, sanitizeFileName(n)]),
      sanitizeMimes: mimes.map((m) => [m, sanitizeMime(m)]),
      reply: { frame: createPeerMessageFrame(reply), preview: makeReplyRef(original).preview },
      privacy,
      invite: { words: inviteWords, mailbox: rv.mailbox, uid: inviterUid, name: 'Ivy', blob: inviteBlob },
    },
    null,
    1,
  ) + '\n',
);
console.log('wrote docs/file-vectors.json', chunks.length, 'chunks');
