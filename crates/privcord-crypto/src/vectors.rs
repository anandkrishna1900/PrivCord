//! The Rust-made vectors in `docs/rust-vectors.json`, built deterministically (test support only).

use crate::{
    backup::seal_backup,
    card::ContactCard,
    channel::{derive_channel, seal_channel_message},
    e2ee::{
        accept_initial_envelope, create_bundle, create_one_time_prekey, create_signed_prekey,
        decrypt_envelope, encrypt_to_envelope, initiate_session, serialize_session,
        validate_bundle, GroupSessionManager, OneTimePrekey, PrekeyInventory, SignedPrekey,
    },
    identity::Identity,
    invite::{derive_invite, seal_invite, InviteKind},
    nostr::{make_event, PutKind},
    peer_auth::{Expected, PeerAuth},
    rng::SeededEntropy,
    seal::{mailbox_for, seal},
    CryptoError,
};
use privcord_domain::{
    pairing::{PairingRecord, PairingStoreState},
    signaling::{ManualSignal, SignalKind},
};
use serde_json::{json, Value};

const ANN: &str =
    "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about";
const BOB: &str = "legal winner thank year wave sausage worth useful legal winner thank yellow";

pub fn build() -> Result<Value, crate::CryptoError> {
    let ann = Identity::from_phrase(ANN, "")?;
    let bob = Identity::from_phrase(BOB, "")?;
    let (ann_uid, bob_uid) = (ann.uid()?, bob.uid()?);
    let mut rng = SeededEntropy::new("privcord-rust-vectors-v1");

    let payload_ab = json!({ "t": "msg", "id": "m-rust-1", "text": "héllo from Rust ✓ 😀", "at": 1_700_000_000_000_i64 });
    let payload_ba = json!({ "t": "offer", "sdp": "v=0\r\ns=-\r\n" });
    let ab = seal(&ann, &bob_uid, &bob.dh_public(), &payload_ab, &mut rng)?;
    let ba = seal(&bob, &ann_uid, &ann.dh_public(), &payload_ba, &mut rng)?;

    let words: Vec<String> = ["apple", "river", "tiger", "moon", "cloud", "seven"]
        .iter()
        .map(|s| (*s).to_owned())
        .collect();
    let rv = derive_invite(&words)?;
    let invite_card = seal_invite(&rv, InviteKind::Card, &ann, Some("Ann"), &mut rng)?;
    let invite_reply = seal_invite(&rv, InviteKind::Reply, &bob, Some("Bob"), &mut rng)?;

    let general = derive_channel("general")?;
    let channel_blob = seal_channel_message(
        &general,
        &ann,
        Some("Ann"),
        "hello from Rust",
        1_700_000_000_123,
        &mut rng,
    )?;

    let backup_data = json!({ "v": 1, "uid": "uid-rust", "messages": ["héllo backup ✓"] });
    let backup = seal_backup(&backup_data, "correct horse battery", &mut rng)?;

    // A legacy WebRTC handshake between the two, made by the Rust implementation.
    let exp = |i: &Identity| -> Result<Expected, CryptoError> {
        Ok(Expected {
            uid: i.uid()?.to_string(),
            sign: i.sign_public(),
            dh: i.dh_public(),
        })
    };
    let mut a = PeerAuth::with_nonce(
        "duo",
        au_str(&ann)?.as_str(),
        "device-ann",
        exp(&bob)?,
        "a1".repeat(24),
    );
    let mut b = PeerAuth::with_nonce(
        "duo",
        au_str(&bob)?.as_str(),
        "device-bob",
        exp(&ann)?,
        "b2".repeat(24),
    );
    let (ha, hb) = (a.hello(&ann)?, b.hello(&bob)?);
    let pa = a.on_frame(&ann, &hb).ok().flatten().unwrap_or_default();
    let pb = b.on_frame(&bob, &ha).ok().flatten().unwrap_or_default();
    let oka = a
        .on_frame(&ann, pb.first().unwrap_or(&Value::Null))
        .ok()
        .flatten()
        .unwrap_or_default();
    let okb = b
        .on_frame(&bob, pa.first().unwrap_or(&Value::Null))
        .ok()
        .flatten()
        .unwrap_or_default();

    let nostr_event = make_event(
        "mailbox-rust",
        &channel_blob,
        PutKind::Sig,
        120,
        1_700_000_000,
        &mut rng,
    )?;
    let manual = ManualSignal {
        kind: SignalKind::Offer,
        conversation_id: "duo".into(),
        from_uid: ann_uid.to_string(),
        from_device_id: "device-ann".into(),
        public_key: ann.sign_public(),
        dh: ann.dh_public(),
        identity_proof: ann.identity_proof()?,
        sdp: "v=0\r\no=- 1 1 IN IP4 127.0.0.1\r\ns=-\r\n".into(),
        nonce: "nonce-0123456789ab".into(),
        created_at: 1_700_000_000_000,
    };
    let pairing = PairingStoreState {
        record: Some(PairingRecord::create(
            bob_uid.as_str(),
            "device-bob",
            bob.sign_public(),
            Some(bob.dh_public()),
            "12345 67890",
            None,
            1_700_000_000_000,
        )),
        auto_reconnect: true,
    };

    let e2ee = build_e2ee(&ann, &bob, &mut rng)?;

    Ok(json!({
        "note": "Generated by crates/privcord-crypto/examples/gen_vectors.rs. Do not edit by hand.",
        "people": {
            "ann": { "phrase": ANN, "uid": ann_uid, "card": ContactCard::of(&ann, Some("Ann ✓"))?.encode()?, "identityProof": ann.identity_proof()?, "mailbox": mailbox_for(ann_uid.as_str()) },
            "bob": { "phrase": BOB, "uid": bob_uid, "card": ContactCard::of(&bob, None)?.encode()?, "identityProof": bob.identity_proof()? }
        },
        "sealed": [
            { "from": "ann", "to": "bob", "payload": payload_ab, "wire": ab.encode() },
            { "from": "bob", "to": "ann", "payload": payload_ba, "wire": ba.encode() }
        ],
        "signature": { "message": "signed by Rust", "by": "ann", "sig": privcord_domain::codec::encode(&ann.sign_message(b"signed by Rust")) },
        "invite": { "words": words, "mailbox": rv.mailbox, "card": invite_card, "reply": invite_reply },
        "peerAuth": { "context": "duo", "annHello": ha, "bobHello": hb, "annProof": pa, "bobProof": pb, "annOk": oka, "bobOk": okb },
        "channel": { "name": "general", "text": "hello from Rust", "blob": channel_blob },
        "nostr": { "mailbox": "mailbox-rust", "blob": channel_blob, "event": nostr_event.to_value() },
        "manual": { "conversation": "duo", "code": manual.encode(), "uid": ann_uid },
        "pairing": { "peer": bob_uid, "serialized": pairing.serialize() },
        "e2ee": e2ee,
        "backup": { "passphrase": "correct horse battery", "text": backup, "data": backup_data }
    }))
}

fn au_str(i: &Identity) -> Result<String, CryptoError> {
    Ok(i.uid()?.to_string())
}

struct Inv(SignedPrekey, OneTimePrekey);
impl PrekeyInventory for Inv {
    fn signed_prekey(&self, id: i64) -> Option<&SignedPrekey> {
        (self.0.id == id).then_some(&self.0)
    }
    fn one_time_prekey(&self, id: i64) -> Option<&OneTimePrekey> {
        (self.1.id == id).then_some(&self.1)
    }
}

/// A short Rust-made conversation (X3DH, ratchet, group message) for the TypeScript tests to read.
fn build_e2ee(
    ann: &Identity,
    bob: &Identity,
    rng: &mut SeededEntropy,
) -> Result<Value, CryptoError> {
    let signed = create_signed_prekey(bob, 7, 1_700_000_000_000, rng)?;
    let one_time = create_one_time_prekey(101, rng)?;
    let bundle = create_bundle(bob, &signed, Some(&one_time))?;
    let bundle_json = bundle.to_value();
    let bundle = validate_bundle(&bundle_json).map_err(CryptoError::E2ee)?;
    let start = initiate_session(ann, &bundle, "r-1", b"hello from Rust", rng)?;
    let mut alice = start.session;
    let alice_after_init = serialize_session(&alice);
    let inv = Inv(signed.clone(), one_time.clone());
    let mut bob_s = accept_initial_envelope(bob, &inv, &start.envelope, rng)?.session;
    let r1 = encrypt_to_envelope(&mut bob_s, "r-2", b"reply from Rust", rng)?;
    let bob_after_reply = serialize_session(&bob_s);
    decrypt_envelope(&mut alice, &r1, rng)?;
    let m3 = encrypt_to_envelope(&mut alice, "r-3", b"second from Rust", rng)?;
    decrypt_envelope(&mut bob_s, &m3, rng)?;

    let mut group = GroupSessionManager::new();
    let epoch_key = GroupSessionManager::generate_epoch_secret(rng)?;
    group.set_group("g-rust", 2);
    group.set_epoch_key("g-rust", 2, epoch_key);
    let gmsg = group.encrypt(
        "g-rust",
        "uid-ann",
        9,
        &json!({ "t": "group hello from Rust" }),
        rng,
    )?;
    Ok(json!({
        "prekeys": {
            "signed": { "id": signed.id, "key": signed.key.to_value(), "signature": signed.signature, "createdAt": signed.created_at },
            "oneTime": { "id": one_time.id, "key": one_time.key.to_value() },
        },
        "bundle": bundle_json,
        "first": start.envelope.to_value(),
        "aliceAfterInit": alice_after_init,
        "reply": r1.to_value(),
        "bobAfterReply": bob_after_reply,
        "second": m3.to_value(),
        "group": { "epochKeyHex": epoch_key.iter().map(|b| format!("{b:02x}")).collect::<String>(), "message": gmsg.to_value() },
    }))
}
